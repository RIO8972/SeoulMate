// 공통 카테고리 단순화기 (토큰 단위 매칭: "회" 같은 오탐 방지)
export default function simplifyCategory(raw = "") {
  const s = String(raw || "").trim();
  if (!s) return "";

  // "사회,공공기관 > 단체,협회" 같은 문자열을 토큰으로 분해
  const tokens = s
    .replace(/\s+/g, "")
    .split(/>|,|\/|·|\(|\)|＆|&|-/g)
    .filter(Boolean);

  const has = (...arr) => tokens.some(t => arr.includes(t));

  if (has("관광","명소","여행","유적","전망대","랜드마크")) return "관광명소";
  if (has("카페","디저트","베이커리","커피")) return "카페";
  //'회' 단독 제외, 명확한 음식 관련 토큰만
  if (has("음식","음식점","식당","한식","중식","양식","일식","분식",
          "치킨","피자","고기","국수","돈까스","횟집","초밥","스시","해산물")) return "음식점";
  if (has("숙박","호텔","모텔","펜션","리조트","게스트하우스","게스트")) return "숙박";
  if (has("쇼핑","시장","백화점","아울렛","마트","편의점","서점")) return "쇼핑";
  if (has("문화","박물관","전시","미술관","공연","도서관","영화관","극장")) return "문화시설";
  if (has("공원","자연","산","호수","강","해변","섬","둘레길","산책로","정원","숲","수목원")) return "자연/공원";

  // 기본: 최상위 토큰(>) 또는 "기타"
  return tokens[0] || "기타";
}
